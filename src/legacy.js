    let currentLang = localStorage.getItem('bhbLang') || 'es';

    function translatePage(lang) {
      if (!translations[lang]) return;

      // Update html lang attribute
      document.documentElement.lang = lang;

      // Update data-i18n (textContent)
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
          el.textContent = translations[lang][key];
        }
      });

      // Update data-i18n-html (innerHTML — safe, we control the content)
      document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (translations[lang][key]) {
          el.innerHTML = translations[lang][key];
        }
      });

      // Update data-i18n-placeholder
      document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
          el.placeholder = translations[lang][key];
        }
      });

      // Update select options with data-i18n
      document.querySelectorAll('select option[data-i18n]').forEach(opt => {
        const key = opt.getAttribute('data-i18n');
        if (translations[lang][key]) {
          opt.textContent = translations[lang][key];
        }
      });

      // Update language switcher buttons
      document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
      });

      // Save preference
      localStorage.setItem('bhbLang', lang);
      currentLang = lang;
    }

    // ─── Language switcher listeners ───
