    // ─── Detect user language on load ───
    (function detectLanguage() {
      // If user already has a saved preference, use it
      const saved = localStorage.getItem('bhbLang');
      if (saved && translations[saved]) {
        translatePage(saved);
        return;
      }
      // Otherwise detect browser language
      const browserLang = (navigator.language || navigator.userLanguage || '').slice(0, 2);
      if (browserLang === 'en') {
        translatePage('en');
      } else if (browserLang === 'pt') {
        translatePage('pt');
      } else {
        translatePage('es');
      }
    })();

